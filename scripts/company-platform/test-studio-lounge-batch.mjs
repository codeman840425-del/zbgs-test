import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {runCompanyBatch} from './batch.mjs';
import {checkManagedOutput} from './package-company.mjs';

const [output,...extra] = process.argv.slice(2);
assert(output && !extra.length,'Use test-studio-lounge-batch.mjs NEW_OUTPUT');
const root = path.resolve(output);
await checkManagedOutput(root,undefined,{allowDelivery:false});
await fs.mkdir(path.dirname(root),{recursive:true});
await fs.mkdir(root);
const source = new URL('./batch-inputs/studio-lounge-set.json',import.meta.url);
const batch = JSON.parse(await fs.readFile(source,'utf8'));
const [rental,office] = batch.items;
const station = rental.studioLoungeSet.station, waiting = rental.studioLoungeSet.waiting;
const primary = station+'/monitor', table = rental.studioLoungeSet.reuse.table;
// A half turn about the installed table's centre preserves its admitted footprint.
const customTable = {position:[-1.30,0,1.60],yaw:Math.PI};
rental.operations.push({type:'set-state',id:primary,state:{on:false}},{type:'move',id:table,transform:customTable});
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const target = path.join(root,'results');
const run = (input,only) => runCompanyBatch(input,{outputDirectory:target,only});
const firstSave = path.join(target,rental.key,'save.json');
const wrongHost = structuredClone(batch);
wrongHost.items[1].studioLoungeSet.station = rental.studioLoungeSet.station;
const refused = await run(wrongHost);
assert.equal(refused.results[0].status,'created',JSON.stringify(refused.results[0]));
assert.equal(refused.results[1].code,'invalid-studio-lounge-set');
assert.equal(refused.results[1].path,'studioLoungeSet.station');
await assert.rejects(fs.access(path.join(target,office.key)),{code:'ENOENT'});
const before = await fs.readFile(firstSave);
const doc = JSON.parse(before).document;
assert.equal(doc.nodes.find(node => node.id === primary).state.on,false);
assert.equal(doc.nodes.find(node => node.id === station+'/desk/secondary-monitor').state.on,true);
assert.deepEqual(doc.nodes.find(node => node.id === table).transform,customTable);
assert.equal(doc.nodes.find(node => node.id === rental.studioLoungeSet.reuse.cup).parentId,table);
const stale = structuredClone(batch);
stale.items[1].studioLoungeSet.recipe.sha256 = '0'.repeat(64);
const badPin = await run(stale,office.key);
assert.equal(badPin.results[0].code,'invalid-studio-lounge-set');
assert.match(badPin.results[0].message,/SHA-256/);
await assert.rejects(fs.access(path.join(target,office.key)),{code:'ENOENT'});
const retry = await run(batch,office.key);
assert.equal(retry.results[0].status,'created');
assert((await fs.readFile(firstSave)).equals(before));
const replay = await run(batch);
assert.deepEqual(replay.results.map(row => row.status),['idempotent','idempotent']);
const report = {ok:true,retained:{primary,primaryOn:false,waiting,table,customTable,saveSha256:hash(before)},
  wrongStation:refused.results[1],badPin:badPin.results[0],retry:retry.results[0],replayed:replay.results.map(row=>row.key)};
await fs.writeFile(path.join(root,'report.json'),JSON.stringify(report,null,2)+'\n',{flag:'wx'});
console.log('Preserved local layout and device state, refused bad host and pin, retried one company and replayed both.');
