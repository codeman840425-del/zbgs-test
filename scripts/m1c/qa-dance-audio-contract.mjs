import assert from 'node:assert/strict';
import {mapDanceAudio,createDanceAudioObserver} from './dance-audio-mapping.mjs';
const state=(time,playback='loop',action='dance')=>({action,dance:{id:'source-loop',time,duration:1,playback}});
const config={audioDurationSeconds:4,loopStartSeconds:1,loopEndSeconds:3,offsetSeconds:.25,loop:true};
const checks=[];
assert.equal(mapDanceAudio(state(.5),config).targetSeconds,1.75);
assert.equal(mapDanceAudio(state(.2),{...config,offsetSeconds:-.3}).status,'waiting-offset');
assert.equal(mapDanceAudio(state(.3),{...config,offsetSeconds:-.3}).targetSeconds,1);
checks.push('Offset sign: positive audio lead, negative silence until cue');
const observer=createDanceAudioObserver(config),a=observer.observe(state(.9)),b=observer.observe(state(1.1));
assert.equal(b.clipWraps,1);assert.equal(b.audioWraps,0);assert(Math.abs(b.targetSeconds-a.targetSeconds-.2)<1e-9);
const c=observer.observe(state(1.9));assert.equal(c.audioWraps,1);assert(Math.abs(c.targetSeconds-1.15)<1e-9);
checks.push('Actual unwrapped clock crosses clip loop without audio restart; audio region wraps separately');
const paused=observer.observe(state(1.9),{paused:true,playbackRate:.25});assert.equal(paused.status,'paused');assert.equal(paused.clockDelta,0);assert.equal(paused.targetSeconds,c.targetSeconds);
const resumed=observer.observe(state(2),{paused:false,playbackRate:.25});assert.equal(resumed.playbackRate,.25);assert(Math.abs(resumed.clockDelta-.1)<1e-9);
checks.push('Paused clock stays fixed; rate is forwarded, never multiplied into actual danceClock twice');
assert.equal(observer.observe(state(.02)).restarted,true);
assert.equal(mapDanceAudio(state(1,'once-then-idle'),config).status,'ended');
assert.equal(mapDanceAudio(state(.9,'loop','idle'),config).status,'inactive');
assert.equal(mapDanceAudio(state(3),{...config,loop:false}).status,'ended');
checks.push('Reset, once completion, fading-out inactive action and nonloop audio end are explicit');
const independent=createDanceAudioObserver(config);assert.equal(independent.observe(state(5)).clockDelta,null);
const drift=createDanceAudioObserver({audioDurationSeconds:2});assert(Math.abs(drift.observe(state(1.99),{},.01).driftSeconds-.02)<1e-9);
assert.equal(independent.observe(state(5)).transportObserved,false);
assert.throws(()=>mapDanceAudio(state(0),{audioDurationSeconds:0}),RangeError);assert.throws(()=>mapDanceAudio(state(NaN),config),TypeError);
checks.push('Instances independent; loop-aware drift measured only when actual transport sample supplied; invalid input rejected');
console.log(JSON.stringify({passed:true,checks,scope:'Pure QA mapping; no product music player, sound, real device latency or audible synchronization verified'},null,2));
