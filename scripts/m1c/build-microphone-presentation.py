"""Build explicit microphone-use targets from measured, versioned lip seams.

Run audit-mic-mouth-anchors.py first. This does not refit the fingers or model.
The authored use offsets require gameplay visual acceptance; they are not
claimed to be a universal microphone technique or an acoustic simulation.
"""
from pathlib import Path
import json, hashlib

ROOT = Path(__file__).resolve().parents[2]
source = ROOT / 'evidence/mic-mouth-target/source-anchors.json'
data = json.loads(source.read_text(encoding='utf-8'))
microphone = data['microphone']
assert microphone['principalAxisLocal'] == [0, 1, 0]
sha = lambda b: hashlib.sha256(b).hexdigest()
profiles = {}
for body in data['bodies']:
    assert sha((ROOT / body['source']).read_bytes()) == body['bodySha256']
    assert sha((ROOT / microphone['source']).read_bytes()) == microphone['sha256']
    profiles[body['bodySha256']] = {
        'id': 'microphone-use-' + body['body'] + '-v1',
        'bodySha256': body['bodySha256'],
        'microphoneSha256': microphone['sha256'],
        'anchorSourceSha256': sha(source.read_bytes()),
        'mouthRawHeadLocal': body['mouthRawHeadLocal'],
        'capsuleLocal': microphone['grilleFrontPoleLocal'],
        # Head-facing coordinates: right-hand side, below mouth, in front.
        # The microphone axis points back to the actual lip seam, not upward.
        'speakingTipOffset': [-.035, -.055, .09],
        'carryWristChestOffset': [-.22, -.18, .24],
        'transitionRate': 10,
    }
output = ROOT / 'prototype/src/microphone-presentation-fits.js'
output.write_text('// Generated by scripts/m1c/build-microphone-presentation.py.\n'
                  '// Exact body and microphone source identities; visual candidate, not universal fit.\n'
                  'export const MICROPHONE_PRESENTATION_FITS = '
                  + json.dumps(profiles, indent=2) + ';\n', encoding='utf-8')
print(output)
